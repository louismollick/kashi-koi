import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { colors, fontFamilies } from '../src/tokens';

const kebab = (name: string) => name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

/**
 * Tailwind v4 `@theme` block for the design tokens: `--color-*` per color, plus `--font-body` and `--font-pixel`
 * (the Fontsource family names the web app loads). The web app generates this into its own
 * `tokens.css` and imports it after `tailwindcss`.
 */
export function tokensCss() {
  const lines = [
    ...Object.entries(colors).map(([name, value]) => `  --color-${kebab(name)}: ${value};`),
    `  --font-body: '${fontFamilies.body}', sans-serif;`,
    `  --font-pixel: '${fontFamilies.pixel}', monospace;`,
  ];
  return `/* Generated by packages/design/scripts/tokens-css.ts. Do not edit by hand. */\n@theme {\n${lines.join('\n')}\n}\n`;
}

// CLI: `tsx scripts/tokens-css.ts <output path>` writes the CSS there.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const target = process.argv[2];
  if (!target) {
    console.error('Usage: tsx tokens-css.ts <output path>');
    process.exit(1);
  }
  writeFileSync(resolve(target), tokensCss());
}
